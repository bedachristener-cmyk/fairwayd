export function validateReviewedAtDirectoryMissingCourses(): string[] {
  const errors: string[] = [];
  const names = new Set<string>();
  const queries = new Set<string>();

  for (const course of REVIEWED_AT_DIRECTORY_MISSING_COURSES) {
    if (!course.name.trim()) errors.push('course name is required');
    if (names.has(course.name)) errors.push(`duplicate name: ${course.name}`);
    names.add(course.name);

    if (!course.searchQuery.trim()) {
      errors.push(`search query is required: ${course.name}`);
    } else if (queries.has(course.searchQuery)) {
      errors.push(`duplicate search query: ${course.searchQuery}`);
    }
    queries.add(course.searchQuery);

    if (!/^[0-9]{4}$/.test(course.postalCode)) {
      errors.push(`invalid Austrian postal code: ${course.name}`);
    }
    if (!Number.isInteger(course.holes) || course.holes < 1 || course.holes > 72) {
      errors.push(`invalid holes value: ${course.name}`);
    }
    if (!/^https:\/\//i.test(course.website)) {
      errors.push(`website must use https: ${course.name}`);
    }
    if (!course.evidence.trim()) {
      errors.push(`evidence is required: ${course.name}`);
    }
  }

  return errors;
}
