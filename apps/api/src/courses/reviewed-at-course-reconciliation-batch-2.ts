export function validateReviewedAtCourseReconciliationBatch2(): string[] {
  const errors: string[] = [];
  const ids = new Set<string>();
  const placeIds = new Set<string>();
  const targetNames = new Set<string>();

  for (const item of REVIEWED_AT_COURSE_RECONCILIATION_BATCH_2) {
    if (
      !item.id ||
      !item.currentName ||
      !item.targetName ||
      !item.placeId ||
      !item.displayName
    ) {
      errors.push('complete course and Google Place metadata is required');
    }
    if (ids.has(item.id)) errors.push(`duplicate course ID: ${item.id}`);
    if (placeIds.has(item.placeId)) {
      errors.push(`duplicate Google Place ID: ${item.placeId}`);
    }
    if (targetNames.has(item.targetName)) {
      errors.push(`duplicate target name: ${item.targetName}`);
    }
    ids.add(item.id);
    placeIds.add(item.placeId);
    targetNames.add(item.targetName);

    for (const [label, lat, lon] of [
      ['current', item.currentLat, item.currentLon],
      ['new', item.newLat, item.newLon],
    ] as const) {
      if (lat < -90 || lat > 90 || lon < -180 || lon > 180) {
        errors.push(`${label} coordinates out of range: ${item.currentName}`);
      }
    }
  }

  for (const item of REVIEWED_AT_INVALID_RECORDS_BATCH_2) {
    if (!item.id || !item.name || !item.reason) {
      errors.push('complete invalid-record metadata is required');
    }
    if (ids.has(item.id)) errors.push(`duplicate course ID: ${item.id}`);
    ids.add(item.id);
    if (
      item.lat < -90 ||
      item.lat > 90 ||
      item.lon < -180 ||
      item.lon > 180
    ) {
      errors.push(`invalid-record coordinates out of range: ${item.name}`);
    }
  }

  return errors;
}
