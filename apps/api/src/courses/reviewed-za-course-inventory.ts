export function isReviewedZaCourseInventoryCandidate(
  row: ZaDiscoveryRow,
): boolean {
  return (
    row.recordType === 'GOOGLE' &&
    row.country === 'ZA' &&
    Boolean(row.placeId.trim()) &&
    !EXCLUDED_EXACT_NAMES.has(row.googleName)
  );
}
