type BaseStringKey = keyof typeof STRINGS.en;
type ExtraStringKey = keyof typeof EXTRA_STRINGS.en;

export type StringKey = BaseStringKey | ExtraStringKey;

const LANG_KEY = "fairwayd_lang";

export function getLang(): Lang {
  const saved = localStorage.getItem(LANG_KEY) as Lang | null;
  if (
    saved === "en" ||
    saved === "de" ||
    saved === "fr" ||
    saved === "it" ||
    saved === "es" ||
    saved === "ko" ||
    saved === "th"
  ) {
    return saved;
  }

  const nav = (navigator.language || "en").toLowerCase();
  if (nav.startsWith("de")) return "de";
  if (nav.startsWith("fr")) return "fr";
  if (nav.startsWith("it")) return "it";
  if (nav.startsWith("es")) return "es";
  if (nav.startsWith("ko")) return "ko";
  if (nav.startsWith("th")) return "th";
  return "en";
}

export function setLang(l: Lang) {
  localStorage.setItem(LANG_KEY, l);
  window.location.reload(); // MVP-simple
}

export function t(key: StringKey): string {
  const lang = getLang();
  const strings = STRINGS[lang] as Record<string, string>;
  const extraStrings = EXTRA_STRINGS[lang] as Record<string, string>;
  const englishStrings = STRINGS.en as Record<string, string>;
  const englishExtraStrings = EXTRA_STRINGS.en as Record<string, string>;

  return (
    strings[key] ??
    extraStrings[key] ??
    englishStrings[key] ??
    englishExtraStrings[key] ??
    key
  );
}
